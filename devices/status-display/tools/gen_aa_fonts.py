#!/usr/bin/env python3
"""Pre-rasterize anti-aliased glyphs for the status display.

The ESP32 renders text by alpha-blending these 8-bit coverage bitmaps into its
off-screen canvas, so there is no runtime font rasterizer and no heap cost.

Usage:
    python3 gen_aa_fonts.py [FONT_DIR] > ../firmware/src/aa_fonts.rs

FONT_DIR must contain Roboto-{Regular,Medium,Bold}.ttf (Apache License 2.0,
https://fonts.google.com/specimen/Roboto); defaults to /usr/share/fonts/TTF.
Requires Pillow built with FreeType.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF")
TEXT_CHARS = "".join(chr(c) for c in range(32, 127)) + "°"

# (rust name, file, pixel size, charset)
FONTS = [
    ("TEMP", "Roboto-Bold.ttf", 40, "-0123456789"),
    ("UNIT", "Roboto-Regular.ttf", 15, TEXT_CHARS),
    ("LABEL", "Roboto-Bold.ttf", 11, TEXT_CHARS),
    ("SMALL", "Roboto-Regular.ttf", 11, TEXT_CHARS),
    ("SMALL_BOLD", "Roboto-Bold.ttf", 11, TEXT_CHARS),
    ("BOOT", "Roboto-Medium.ttf", 16, TEXT_CHARS),
]


def rasterize(font, ch):
    """Returns (advance in 1/16 px, ink x/y offset from the pen on the
    baseline, ink width/height, 8-bit coverage rows)."""
    adv16 = round(font.getlength(ch) * 16)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    pad = 4
    img = Image.new("L", (x1 - x0 + 2 * pad, y1 - y0 + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad - x0, pad - y0), ch, font=font, fill=255, anchor="ls")
    ink = img.getbbox()
    if ink is None:
        return adv16, 0, 0, 0, 0, b""
    l, t, r, b = ink
    crop = img.crop(ink)
    return adv16, l - pad + x0, t - pad + y0, r - l, b - t, crop.tobytes()


def main():
    out = [
        "// @generated by devices/status-display/tools/gen_aa_fonts.py -- do not edit.",
        "// Glyphs rasterized from Roboto (Apache License 2.0).",
        "",
        "use crate::aa_text::{AaFont, Glyph};",
        "",
    ]
    for name, file, size, chars in FONTS:
        font = ImageFont.truetype(str(FONT_DIR / file), size)
        glyphs, data = [], bytearray()
        for ch in sorted(set(chars)):
            adv16, x, y, w, h, bits = rasterize(font, ch)
            glyphs.append((ch, adv16, x, y, w, h, len(data)))
            data += bits
        out.append(f"static {name}_GLYPHS: [Glyph; {len(glyphs)}] = [")
        for ch, adv16, x, y, w, h, off in glyphs:
            out.append(
                f"    Glyph {{ ch: {ch!r}, adv16: {adv16}, x: {x}, y: {y}, w: {w}, h: {h}, off: {off} }},"
                .replace(f"ch: {ch!r}", "ch: '" + ("\\'" if ch == "'" else "\\\\" if ch == "\\" else ch) + "'")
            )
        out.append("];")
        hexdata = ",".join(str(b) for b in data)
        out.append(f"static {name}_DATA: [u8; {len(data)}] = [{hexdata}];")
        out.append(
            f"pub static {name}: AaFont = AaFont {{ glyphs: &{name}_GLYPHS, data: &{name}_DATA }};"
        )
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
